Future<void> main() async {
  final entries = await Directory('lib/core/localization/strings')
      .list()
      .toList();
  for (final e in entries) {
    if (e is! File ||
        !e.path.contains('strings_') ||
        !e.path.endsWith('.dart')) {
      continue;
    }
    final file = e;
    final lang = file.uri.pathSegments.last
        .replaceFirst('strings_', '')
        .replaceFirst('.dart', '');
    if (lang == 'en') continue;
    final text = utf8.decode(await file.readAsBytes());
    final existing = RegExp(r'L10nKeys\.(\w+)\s*:')
        .allMatches(text)
        .map((m) => m.group(1)!)
        .toSet();
    final missing = <String, String>{};
    for (final key in en.stringsEn.keys) {
      if (existing.contains(key)) continue;
      missing[key] = _authored(lang, key) ?? en.stringsEn[key]!;
    }
    if (missing.isEmpty) continue;
    final block = StringBuffer();
    for (final e in missing.entries) {
      block.writeln("  L10nKeys.${e.key}: '${_escape(e.value)}',");
    }
    final idx = text.lastIndexOf('};');
    final updated =
        '${text.substring(0, idx)}\n${block.toString()}${text.substring(idx)}';
    await file.writeAsString(updated, encoding: utf8);
    stdout.writeln(
      '${file.uri.pathSegments.last}: backfilled ${missing.length} keys',
    );
  }
}

/// Looks up an authored translation for [key] in [lang], or `null` when only
/// the English fallback text is available.
String? _authored(String lang, String key) {
  for (var i = 0; i < _careServer.length; i++) {
    if (_careServer[i][0] == key) return _major[lang]?[i];
  }
  if (lang == 'brx') return _brxAuth[key];
  if (lang == 'sat' && key == 'careUploadPhoto') return 'Upload photo';
  return null;
}

String _escape(String value) =>
    value.replaceAll(r'\', r'\\').replaceAll("'", r"\'");
